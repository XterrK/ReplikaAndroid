#!/usr/bin/env python3
"""Generate tiny original synthetic codec/timestamp fixtures. No speech/ASR quality claim."""
import argparse
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT=pathlib.Path(__file__).resolve().parents[1]

def native_path(path):
    path=pathlib.Path(path).resolve()
    if str(path).startswith('/mnt/') and len(path.parts)>3:
        return path.parts[2].upper()+':/'+ '/'.join(path.parts[3:])
    return str(path)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ffmpeg',default='/mnt/f/ReplikaToolchain/ffmpeg/ffmpeg-9.0.2-essentials_build/bin/ffmpeg.exe')
    parser.add_argument('--output',type=pathlib.Path,default=ROOT/'app/src/androidTest/assets/media-import')
    args=parser.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    video=['-f','lavfi','-i','color=c=0x6979ae:s=64x64:r=10:d=1.4']
    audio=['-f','lavfi','-i','sine=frequency=440:sample_rate=48000:duration=1.0']
    cases={
      'aac-zero.mp4':video+audio+['-map','0:v','-map','1:a','-c:v','mpeg4','-q:v','8','-c:a','aac','-b:a','48k','-avoid_negative_ts','make_zero'],
      'aac-priming.mp4':video+audio+['-map','0:v','-map','1:a','-c:v','mpeg4','-q:v','8','-c:a','aac','-b:a','48k'],
      'aac-offset.mp4':video+['-itsoffset','0.4']+audio+['-map','0:v','-map','1:a','-c:v','mpeg4','-q:v','8','-c:a','aac','-b:a','48k'],
      'no-audio.mp4':video+['-an','-c:v','mpeg4','-q:v','8'],
      'multi-audio.mp4':video+audio+['-f','lavfi','-i','sine=frequency=1000:sample_rate=48000:duration=1.0','-map','0:v','-map','1:a','-map','2:a','-c:v','mpeg4','-q:v','8','-c:a','aac','-b:a','48k','-disposition:a:0','0','-disposition:a:1','default','-avoid_negative_ts','make_zero'],
      'opus-fallback.webm':video+audio+['-map','0:v','-map','1:a','-c:v','libvpx-vp9','-deadline','realtime','-cpu-used','8','-b:v','20k','-c:a','libopus','-b:a','32k'],
      'audio-only.m4a':audio+['-c:a','aac','-b:a','48k'],
    }
    inventory=[]
    for name,options in cases.items():
        destination=args.output/name
        target=native_path(destination) if args.ffmpeg.endswith('.exe') else str(destination)
        subprocess.run([args.ffmpeg,'-y','-hide_banner','-loglevel','error',*options,target],check=True)
        inventory.append(dict(path=name,bytes=destination.stat().st_size,sha256=hashlib.sha256(destination.read_bytes()).hexdigest()))
    (args.output/'fixtures.json').write_text(json.dumps({'kind':'synthetic tone and original flat-color video generated by FFmpeg; no speech; no quality/phone validation','license':'CC0 original generated fixture data','files':inventory},indent=2)+'\n')
    print(json.dumps(inventory,indent=2))


if __name__=='__main__':main()
